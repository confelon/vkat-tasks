"""Все настраиваемые параметры проекта в одном месте.

Обычного dataclass достаточно: нет пользовательского ввода и окружения,
которые нужно проверять. Чтобы изменить запуск, правим значения ниже —
в dev-контейнере файл примонтирован, изменения подхватываются сразу.
"""

from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class ProjectConfig:
    # --- Базовая модель ---------------------------------------------------
    # Qwen2.5-0.5B — именно base, а не Instruct: её не учили отвечать на
    # инструкции, поэтому эффект дообучения виден в сравнении «до/после».
    model_name: str = "Qwen/Qwen2.5-0.5B"

    # --- Датасет ----------------------------------------------------------
    dataset_name: str = "yahma/alpaca-cleaned"
    dataset_split: str = "train"
    # Полный датасет — 51 760 строк. Берём подмножество, чтобы один прогон
    # занимал минуты.
    max_samples: int = 1000
    # Длина последовательности: память attention растёт квадратично, память
    # logits — линейно. 512 токенов покрывает почти все строки Alpaca.
    max_seq_len: int = 512

    # --- Обучение ---------------------------------------------------------
    epochs: int = 1
    learning_rate: float = 2e-4
    # Эффективный батч = batch_size * grad_accum_steps = 16 примеров на шаг.
    # В памяти GPU одновременно только batch_size; накопление градиента
    # суммирует несколько маленьких батчей перед обновлением весов.
    batch_size: int = 2
    grad_accum_steps: int = 8

    # --- LoRA -------------------------------------------------------------
    lora_r: int = 8
    lora_alpha: int = 16
    lora_dropout: float = 0.0
    # Четыре проекции attention в архитектуре Qwen2. LoRA вешается только на
    # них, всё остальное заморожено.
    lora_target_modules: list[str] = field(
        default_factory=lambda: ["q_proj", "k_proj", "v_proj", "o_proj"]
    )

    # --- Пути -------------------------------------------------------------
    output_dir: Path = Path("output")
    # Результат обучения: только адаптер, несколько мегабайт.
    adapter_dir: Path = Path("output/adapter")
    # То, что раздаёт vLLM: база с влитым адаптером, около 1 GB.
    merged_dir: Path = Path("output/merged")
